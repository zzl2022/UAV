H2('2.2 建筑体块生成')
P('建筑采用 LoD1 体块。河南博物院片区的每栋建筑保留外环和内环，顶点在预处理阶段已转为局部米制坐标；底面高程 base 取轮廓顶点 DEM 采样的最大值，基础底面取最小值，屋顶高程为 base 加 DBF 高度；顶面和底面用 THREE.ShapeUtils.triangulateShape 三角化，内环作为孔洞，每个环的相邻顶点生成两个三角形形成封闭侧墙。几何转为 non-indexed 后重新计算法线。所有建筑合并为一个 BufferGeometry，并按建筑记录三角面区间，拾取时由面序号反查建筑。郑州场景 15,889 栋建筑生成 424,084 个三角面，平均每栋约 27 个。')
