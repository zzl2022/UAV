import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createModel} from '../src/model.js';
import {createSceneQuery} from '../src/sensors/scene.js';
import {optimizeDeployment,DEFAULT_SETTINGS,scenarios} from '../src/planning/optimizer.js';
import {enrichReport} from '../src/planning/report.js';
import {buildFlightRoute,simulateFlight} from '../src/planning/flight.js';
const root=new URL('../',import.meta.url);
const city=JSON.parse(await readFile(new URL('public/data/city.json',root))),terrain=JSON.parse(await readFile(new URL('public/data/terrain.json',root)));
const query=createSceneQuery(createModel(city,terrain));
const settings={...DEFAULT_SETTINGS,scope:process.argv.includes('--core')?'core':'city'};
let last=0;const progress=p=>{if(Date.now()-last>5000){console.log(`${p.stage}: ${p.completed}/${p.total} (${p.samples??''})`);last=Date.now();}};
const yieldTask=()=>new Promise(resolve=>setImmediate(resolve));
const report=await optimizeDeployment({city,query,settings,progress,yieldTask});
const selected=report.plans.find(p=>p.id===report.selectedId);
console.log('Selected plan:',selected.name,'devices',selected.devices.length,'cost',selected.cost,'coverage',selected.metrics.map(m=>[m.condition,m.coverageRate]));
report.route=buildFlightRoute(query,report.sampling.bounds);
report.flight=await simulateFlight({query,devices:selected.devices,route:report.route,target:{...report.target,...scenarios(report.environment)[0].target},environment:report.environment,core:report.sampling.bounds.core,coreRadius:settings.coreRadius,progress,yieldTask});
enrichReport(report,city);
await mkdir(new URL('artifacts/',root),{recursive:true});
await writeFile(new URL('artifacts/deployment-report.json',root),JSON.stringify(report));
if(process.argv.includes('--example'))await writeFile(new URL('public/deployment-example.json',root),JSON.stringify(report));
console.log(JSON.stringify({samples:report.sampling.samples.length,candidates:report.candidateCount,selected:selected.name,devices:selected.devices.length,metrics:selected.metrics,flight:report.flight.summary,durationMs:report.durationMs},null,2));
