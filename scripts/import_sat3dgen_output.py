"""Copy Sat3DGen results into public/data/sat3dgen and write a manifest."""
from pathlib import Path
import argparse
import hashlib
import json
import shutil
import time

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'public/data/sat3dgen'
DEFAULT_INPUT = ROOT / 'artifacts/sat3dgen/input/zhengzhou_museum.png'
DEFAULT_RESULTS = ROOT / 'artifacts/sat3dgen/results/zhengzhou_museum'

FILES = {
    'mesh.obj': 'mesh',
    'streetview_video.mp4': 'streetviewVideo',
    'panorama_video.mp4': 'panoramaVideo',
    'mesh_orbit_video.mp4': 'orbitVideo',
    'demo_video.mp4': 'demoVideo',
    'space_video.mp4': 'demoVideo',
    'trajectory.csv': 'trajectory',
    'pred_satrgb.png': 'satelliteRender',
    'pred_street.png': 'streetImage',
    'pred_sky.png': 'skyImage',
}


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', type=Path, default=DEFAULT_RESULTS,
                        help='Sat3DGen results/demo/<image_stem> directory')
    parser.add_argument('--satellite', type=Path, default=DEFAULT_INPUT)
    parser.add_argument('--out', type=Path, default=OUT)
    parser.add_argument('--center', type=float, nargs=2,
                        default=[113.66613626120788, 34.789408907490646])
    parser.add_argument('--size', type=int, default=640)
    parser.add_argument('--resolution', type=int, default=256,
                        help='Sat3DGen mesh voxel resolution')
    parser.add_argument('--full', action='store_true',
                        help='import a full-extent overview mesh as mesh_full.obj')
    args = parser.parse_args()

    if not args.input.exists():
        raise SystemExit(f'Sat3DGen output directory not found: {args.input}')
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / 'input').mkdir(parents=True, exist_ok=True)
    if args.satellite.exists():
        shutil.copy2(args.satellite, args.out / 'input' / args.satellite.name)

    if args.full:
        manifest_path = args.out / 'manifest.json'
        if manifest_path.exists():
            manifest = json.loads(manifest_path.read_text(encoding='utf-8'))
        else:
            manifest = {
                'status': 'ready',
                'generatedAt': time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime()),
                'model': 'Sat3DGen (ICLR 2026)',
                'license': 'MIT (Sat3DGen); generated outputs for research/demo use',
                'center': args.center,
                'size': 1024,
                'satellite': f'input/{args.satellite.name}',
                'source': 'Sat3DGen full-extent overview',
                'files': {},
                'notes': [],
            }
        source = args.input / 'mesh.obj'
        if not source.exists():
            raise SystemExit(f'No mesh.obj in {args.input}')
        target = args.out / 'mesh_full.obj'
        shutil.copy2(source, target)
        manifest.setdefault('files', {})['fullMesh'] = {
            'path': target.name, 'bytes': target.stat().st_size,
            'sha256': sha256(target),
        }
        manifest['fullMesh'] = target.name
        manifest['fullResolution'] = args.resolution
        manifest['fullSatellite'] = f'input/{args.satellite.name}'
        manifest['fullSource'] = 'Sat3DGen full-extent overview (padded)'
        manifest['status'] = 'ready'
        manifest.setdefault('notes', []).append(
            'The full-extent overview covers the orthophoto extent but is coarser '
            'than the detail mesh; use the detail mesh for the museum area.')
        manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2),
                                 encoding='utf-8')
        print(f'Imported full-extent mesh to {target}')
        print(f'Updated {manifest_path}')
        return

    manifest = {
        'status': 'ready',
        'generatedAt': time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime()),
        'model': 'Sat3DGen (ICLR 2026)',
        'license': 'MIT (Sat3DGen); generated outputs for research/demo use',
        'center': args.center,
        'size': args.size,
        'resolution': args.resolution,
        'satellite': f'input/{args.satellite.name}',
        'source': 'Sat3DGen single-image inference',
        'files': {},
        'notes': [
            'Street view and panorama are generated by Sat3DGen, not real street-level imagery.',
            'The mesh is in the satellite crop frame, not georeferenced to the 天地图 basemap.',
            'Sat3DGen is a research model; geometry is approximate and not survey-grade.',
        ],
    }
    copied = []
    for name, key in FILES.items():
        source = args.input / name
        if not source.exists():
            continue
        target = args.out / name
        shutil.copy2(source, target)
        manifest['files'][key] = {
            'path': name, 'bytes': target.stat().st_size,
            'sha256': sha256(target),
        }
        if key in ('mesh', 'streetviewVideo', 'panoramaVideo', 'orbitVideo',
                   'demoVideo', 'streetImage', 'skyImage', 'satelliteRender'):
            manifest[key] = name
        if key == 'trajectory':
            manifest['trajectory'] = name
        copied.append(name)
    if 'mesh' not in manifest:
        raise SystemExit('No mesh.obj found in Sat3DGen output; nothing was imported')
    if 'demoVideo' in manifest and 'streetviewVideo' not in manifest:
        # The public Space returns one composed 2x2 video rather than separate
        # street-view/panorama files.
        manifest['streetviewVideo']=manifest['demoVideo']
    manifest_path = args.out / 'manifest.json'
    if manifest_path.exists():
        existing = json.loads(manifest_path.read_text(encoding='utf-8'))
        for key in ('fullMesh', 'fullResolution', 'fullSatellite', 'fullSource'):
            if key in existing:
                manifest[key] = existing[key]
        if 'fullMesh' in existing.get('files', {}):
            manifest['files']['fullMesh'] = existing['files']['fullMesh']
    manifest_path.write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2), encoding='utf-8')
    print(f'Imported {len(copied)} files: {", ".join(copied)}')
    print(f'Wrote {args.out / "manifest.json"}')


if __name__ == '__main__':
    main()
